/**
 * generate-assets.ts
 *
 * Emits the three distribution packages that are derived from the registry:
 *
 *   @bci-av/assets   one .svg file per symbol
 *   @bci-av/sprite   an SVG symbol sheet plus an id map
 *   @bci-av/css      one background-image class per symbol
 *
 * Run after `yarn generate`, which produces the registry these read from.
 *
 * Deliberately no raster variants. The sibling repos rasterise every pictogram
 * to jpg/png/webp at five sizes, which at 6,551 symbols would be 98,265 files;
 * that is the pattern that left road-signs with a 16GB asset tree and tarballs
 * too large for npm to accept. Blissymbols are line drawings that scale
 * perfectly as SVG, so there is nothing to gain from it.
 *
 * Usage: yarn generate-assets
 */

import fs from 'node:fs';
import path from 'node:path';
import { symbols } from '../packages/@bci-av/core/src/symbols.generated';

const PKG = path.join('packages', '@bci-av');
const ASSETS_DIR = path.join(PKG, 'assets', 'assets');
const SPRITE_DIR = path.join(PKG, 'sprite');
const CSS_DIR = path.join(PKG, 'css');

/** Removes previously generated output so a renamed symbol cannot linger. */
const resetDir = (dir: string): void => {
  fs.rmSync(dir, { recursive: true, force: true });
  fs.mkdirSync(dir, { recursive: true });
};

const writeAssets = (): number => {
  resetDir(ASSETS_DIR);
  for (const symbol of symbols) {
    fs.writeFileSync(path.join(ASSETS_DIR, `${symbol.id}.svg`), symbol.svg, 'utf-8');
  }
  return symbols.length;
};

const writeSprite = (): void => {
  fs.mkdirSync(SPRITE_DIR, { recursive: true });

  const parts: string[] = [
    '<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" style="display:none">',
  ];
  const ids: Record<string, string> = {};

  for (const symbol of symbols) {
    const id = `bliss-${symbol.id}`;
    ids[symbol.id] = id;
    // <symbol> carries the viewBox and the children; the wrapping <svg> element
    // and its attributes are dropped.
    const viewBox = /viewBox="([^"]*)"/.exec(symbol.svg)?.[1] ?? '';
    const inner = symbol.svg.replace(/^<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
    parts.push(`<symbol id="${id}" viewBox="${viewBox}">${inner}</symbol>`);
  }
  parts.push('</svg>');

  fs.writeFileSync(path.join(SPRITE_DIR, 'sprite.svg'), parts.join('\n'), 'utf-8');
  fs.writeFileSync(
    path.join(SPRITE_DIR, 'sprite-ids.json'),
    `${JSON.stringify(ids, null, 2)}\n`,
    'utf-8',
  );
};

const writeCss = (): void => {
  fs.mkdirSync(CSS_DIR, { recursive: true });

  const lines = [
    '/* Blissymbolics — CSS sprite',
    "   Generated by 'yarn generate-assets'. Do not edit manually.",
    '',
    '   Apply a class to a sized block element:',
    '     <span class="bliss-house-work" style="display:inline-block;width:64px;height:64px"></span>',
    '',
    '   Backgrounds reference @bci-av/assets, so install it alongside this',
    '   package. Inlining 6,551 data URIs instead would make this file ~4MB. */',
    '',
  ];
  for (const symbol of symbols) {
    lines.push(
      `.bliss-${symbol.id} {`,
      `  background-image: url('../assets/assets/${symbol.id}.svg');`,
      '  background-position: center;',
      '  background-repeat: no-repeat;',
      '  background-size: contain;',
      '}',
      '',
    );
  }
  fs.writeFileSync(path.join(CSS_DIR, 'sprite.css'), lines.join('\n'), 'utf-8');
};

const mb = (file: string): string => `${(fs.statSync(file).size / 1048576).toFixed(1)} MB`;

const main = (): void => {
  const count = writeAssets();
  writeSprite();
  writeCss();

  console.log(`assets  ${count} files in ${ASSETS_DIR}`);
  console.log(`sprite  ${mb(path.join(SPRITE_DIR, 'sprite.svg'))} sprite.svg + sprite-ids.json`);
  console.log(`css     ${mb(path.join(CSS_DIR, 'sprite.css'))} sprite.css`);
};

main();
